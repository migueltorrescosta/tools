	<summary>How it works</summary>
	<p>
		Pick a preset or build a setup, then press Run. The optimiser finds the best controls for the
		ancilla scheme and for a plain Mach-Zehnder interferometer, with the same particles, noise and
		hold time. An R above 1 means the ancilla helps. The Rules panel shows which fairness rules
		hold.
	</p>
	<p>
		The model, the rules and the metrics are in the
		<a href="https://github.com/migueltorrescosta/tools/blob/main/docs/ancilla-mzi.md">docs</a>.
	</p>
</details>
